import type { ScoreRule, ScoreTableEntry } from '../types'

/** 官方表“3'40"”为 3 分 40 秒。 */
export function zhuhaiClockToSeconds(value: string): number {
  const match = value.trim().match(/^(\d+)[':](\d{2})"?$/)
  if (!match) {
    throw new Error(`无法解析珠海时间档 ${value}`)
  }
  return Number(match[1]) * 60 + Number(match[2])
}

function linearRule(maxScore: number, entries: ScoreTableEntry[]): ScoreRule {
  return {
    kind: 'thresholdTable',
    scoreMode: 'linear',
    maxScore,
    minScore: 0,
    entries
  }
}

