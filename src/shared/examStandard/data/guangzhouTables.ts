import type { ScoreRule, ScoreTableEntry } from '../types'

function row(score: number, threshold: number): ScoreTableEntry {
  return { score, threshold }
}

function ms(minutes: number, seconds: number): number {
  return minutes * 60 + seconds
}

export function linearRule(entries: ScoreTableEntry[]): ScoreRule {
  return {
    kind: 'thresholdTable',
    scoreMode: 'linear',
    maxScore: 100,
    minScore: 0,
    entries
  }
}

